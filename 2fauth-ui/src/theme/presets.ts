import type { ThemeConfig } from './types'

const sans = "'Inter', 'Segoe UI', system-ui, -apple-system, 'Helvetica Neue', sans-serif"
const mono = "'JetBrains Mono', 'SFMono-Regular', ui-monospace, 'Cascadia Mono', Menlo, monospace"

function preset(
  id: string,
  name: string,
  base: 'dark' | 'light',
  palette: Partial<ThemeConfig['palette']>,
  rest: Partial<Omit<ThemeConfig, 'palette' | 'id' | 'name' | 'base'>> = {},
): ThemeConfig {
  return {
    id,
    name,
    base,
    palette: {
      bg: '#05070f',
      bg2: '#080d18',
      glowA: '#6ea8ff',
      glowB: '#b07cff',
      glowC: '#55e6c1',
      panel: '#101727',
      panelAlpha: 0.72,
      panelStrong: '#0b111e',
      border: '#78a0ff',
      borderStrong: '#9ec0ff',
      text: '#e8eefc',
      muted: '#8f9dbb',
      accent: '#55e6c1',
      accent2: '#6ea8ff',
      accent3: '#b07cff',
      danger: '#ff6b81',
      warn: '#ffc46b',
      ...palette,
    },
    surface: { radius: 18, blur: 22, cardGradient: true, ...(rest.surface ?? {}) },
    typography: { sans, mono, scale: 1, ...(rest.typography ?? {}) },
    motion: { enabled: true, duration: 180, autoRotate: false, ...(rest.motion ?? {}) },
    background: { style: 'grid', intensity: 1, speed: 1, ...(rest.background ?? {}) },
  }
}

